"""Factory for read-only rank ViewSets — all four rank models share the same shape."""
from rest_framework import viewsets, serializers, permissions
from calculatorapi.models import (
    ClubRank,
    TeamTrialsRank,
    ChampionsMeetingRank,
    LeagueOfHeroesRank,
)

_RANK_FIELDS = ("id", "name", "income_amount")
# CM and LoH ranks also award tickets and shards per event, and carry the
# payouts that change from a later event on (`rewards`; prefetch it).
_COMPETITIVE_RANK_FIELDS = (
    "id", "name", "income_amount",
    "uma_ticket_amount", "support_ticket_amount",
    "ssr_shard_amount", "sr_shard_amount",
    "rewards",
)


class RaceRankRewardSerializer(serializers.Serializer):  # pylint: disable=abstract-method
    """One "from event #N, pays X" row (models/race_rank_reward.py). Read-only,
    and shared by both kinds, which have the same two fields."""
    from_event_number = serializers.IntegerField()
    income_amount = serializers.IntegerField()


def _make_rank_serializer(model, fields=_RANK_FIELDS, declared=None):
    """Return a ModelSerializer class for the given rank model.

    Uses type() to build the Meta class before the serializer class so that
    DRF's metaclass sees a fully-configured Meta at class-creation time.
    `declared` adds fields that aren't plain model columns (a nested list).
    """
    meta = type("Meta", (), {"model": model, "fields": fields})
    return type(
        f"{model.__name__}Serializer",
        (serializers.ModelSerializer,),
        {"Meta": meta, **(declared or {})},
    )


def _competitive_rank_serializer(model):
    """A CM or LoH rank's serializer: the competitive fields plus `rewards`.
    Each gets its own nested field instance rather than sharing one."""
    return _make_rank_serializer(
        model,
        _COMPETITIVE_RANK_FIELDS,
        declared={"rewards": RaceRankRewardSerializer(many=True, read_only=True)},
    )


def _make_rank_viewset(model, serializer_class, ordering="income_amount", prefetch=()):
    """Return a ReadOnlyModelViewSet for the given rank model.

    `ordering` is the field the endpoint sorts by. It defaults to
    "income_amount" (logical for ranks whose income rises with their tier),
    but Champions Meeting placements don't sort logically by income, so that
    model passes its explicit "sort_order" field instead. `prefetch` names
    the related lists the serializer reads, so they cost one query, not one
    per rank.
    """
    class _ViewSet(  # pylint: disable=too-many-ancestors,too-few-public-methods
        viewsets.ReadOnlyModelViewSet
    ):
        """Read-only ViewSet generated by _make_rank_viewset."""
        queryset = model.objects.prefetch_related(*prefetch).order_by(ordering)
        # Pure reference data — readable by guests.
        permission_classes = [permissions.AllowAny]

    _ViewSet.serializer_class = serializer_class
    _ViewSet.__name__ = f"{model.__name__}ViewSet"
    return _ViewSet


ClubRankSerializer = _make_rank_serializer(ClubRank)
TeamTrialsRankSerializer = _make_rank_serializer(TeamTrialsRank)
ChampionsMeetingRankSerializer = _competitive_rank_serializer(ChampionsMeetingRank)
LeagueOfHeroesRankSerializer = _competitive_rank_serializer(LeagueOfHeroesRank)

ClubRankViewSet = _make_rank_viewset(ClubRank, ClubRankSerializer)
TeamTrialsRankViewSet = _make_rank_viewset(TeamTrialsRank, TeamTrialsRankSerializer)
ChampionsMeetingRankViewSet = _make_rank_viewset(
    ChampionsMeetingRank, ChampionsMeetingRankSerializer, ordering="sort_order",
    prefetch=("rewards",),
)
LeagueOfHeroesRankViewSet = _make_rank_viewset(
    LeagueOfHeroesRank, LeagueOfHeroesRankSerializer, prefetch=("rewards",),
)
